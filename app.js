async function detectLanguageByIP() {
    let country = '';
    try {
        const response = await fetch('https://freeipapi.com/api/json');
        const data = await response.json();
        country = data?.countryCode;
    } catch (e) {
        try {
            const response = await fetch('https://ipapi.co/json/');
            const data = await response.json();
            country = data?.country_code;
        } catch (err) {
            console.error('IP Geolocation failed:', err);
        }
    }

    if (country) {
        const countryCode = country.toUpperCase();
        let detectedLang = 'en';
        if (['UZ', 'TJ', 'KG', 'KZ'].includes(countryCode)) {
            detectedLang = 'uz';
        } else if (countryCode === 'RU') {
            detectedLang = 'ru';
        }
        window.setLang(detectedLang);
    }
}

function animateLoaderProgress(onComplete) {
    const loaderText = document.getElementById('loader-text');
    const progressBar = document.getElementById('loader-progress-bar');
    if (!loaderText || !progressBar) {
        onComplete();
        return;
    }

    let progress = 0;
    const duration = 1500; // 1.5 seconds loading time
    const intervalTime = 30; // update every 30ms
    const steps = duration / intervalTime;
    const increment = 100 / steps;

    const timer = setInterval(() => {
        progress += increment;
        if (progress >= 100) {
            progress = 100;
            clearInterval(timer);
            
            loaderText.textContent = '100%';
            progressBar.style.width = '100%';
            setTimeout(onComplete, 300);
        } else {
            const displayProgress = Math.floor(progress);
            loaderText.textContent = `${displayProgress}%`;
            progressBar.style.width = `${displayProgress}%`;
        }
    }, intervalTime);
}

