function applyTranslations() {
    const dictionary = translations[activeLang] || translations.uz;
    document.documentElement.lang = activeLang;
    document.title = dictionary.page_title;

    const metaDescription = document.querySelector('meta[name="description"]');
    const ogDescription = document.querySelector('meta[property="og:description"]');
    if (metaDescription) metaDescription.setAttribute('content', dictionary.meta_desc);
    if (ogDescription) ogDescription.setAttribute('content', dictionary.hero_desc);

    document.querySelectorAll('[data-i18n]').forEach((el) => {
        const key = el.getAttribute('data-i18n');
        if (dictionary[key]) el.textContent = dictionary[key];
    });

    document.querySelectorAll('.lang-btn, .lang-btn-m').forEach((btn) => {
        const isActive = btn.id === `lang-${activeLang}` || btn.id === `lang-${activeLang}-m`;
        btn.classList.toggle('lang-active', isActive && btn.classList.contains('lang-btn'));
        btn.classList.toggle('lang-active-m', isActive && btn.classList.contains('lang-btn-m'));
    });

    document.querySelectorAll('[data-lang-menu]').forEach((menu) => {
        const activeOption = languageOptions[activeLang] || languageOptions.uz;
        const trigger = menu.querySelector('[data-lang-trigger]');
        const isCompact = trigger?.classList.contains('compact-trigger');
        if (trigger) {
            trigger.innerHTML = `
                <img class="flag-img" src="${activeOption.flag}" alt="">
                <span>${isCompact ? activeOption.short : activeOption.label}</span>
                <i class="fas fa-chevron-down" aria-hidden="true"></i>
            `;
        }

        menu.querySelectorAll('[data-lang-option]').forEach((option) => {
            const lang = option.getAttribute('data-lang-option');
            const flagImg = option.querySelector('[data-flag]');
            if (flagImg && languageOptions[lang]) {
                flagImg.src = languageOptions[lang].flag;
            }
            const isSelected = lang === activeLang;
            option.classList.toggle('selected', isSelected);
            option.setAttribute('aria-selected', isSelected ? 'true' : 'false');
        });
    });
}

window.setLang = function setLang(lang, isUserAction = false) {
    if (!translations[lang]) return;
    activeLang = lang;
    localStorage.setItem('salesnews_lang', lang);
    if (isUserAction) {
        localStorage.setItem('salesnews_lang_by_user', 'true');
    }
    applyTranslations();
    renderProducts(currentProductCategory);
    setupTeamCarousel();
};

function initLanguageMenus() {
    document.querySelectorAll('[data-lang-menu]').forEach((menu) => {
        const trigger = menu.querySelector('[data-lang-trigger]');
        if (!trigger || menu.dataset.initialized === 'true') return;

        trigger.addEventListener('click', (event) => {
            event.stopPropagation();
            const isOpen = menu.classList.toggle('open');
            trigger.setAttribute('aria-expanded', isOpen ? 'true' : 'false');
        });

        menu.querySelectorAll('[data-lang-option]').forEach((option) => {
            option.addEventListener('click', (event) => {
                event.stopPropagation();
                window.setLang(option.getAttribute('data-lang-option'), true);
                menu.classList.remove('open');
                trigger.setAttribute('aria-expanded', 'false');
            });
        });

        menu.dataset.initialized = 'true';
    });

    document.addEventListener('click', () => {
        document.querySelectorAll('[data-lang-menu].open').forEach((menu) => {
            menu.classList.remove('open');
            menu.querySelector('[data-lang-trigger]')?.setAttribute('aria-expanded', 'false');
        });
    });
}

function getInitialTheme() {
    const savedTheme = localStorage.getItem('salesnews_theme');
    if (savedTheme === 'dark' || savedTheme === 'light') return savedTheme;
    return window.matchMedia?.('(prefers-color-scheme: dark)').matches ? 'dark' : 'light';
}

function applyTheme(theme) {
    const normalizedTheme = theme === 'dark' ? 'dark' : 'light';
    document.documentElement.dataset.theme = normalizedTheme;
    document.body.dataset.theme = normalizedTheme;
    document.querySelectorAll('[data-theme-toggle]').forEach((button) => {
        const icon = button.querySelector('i');
        if (icon) {
            icon.className = normalizedTheme === 'dark' ? 'fa-solid fa-sun' : 'fa-solid fa-moon';
        }
        button.setAttribute('aria-label', normalizedTheme === 'dark' ? 'Light mode' : 'Dark mode');
        button.setAttribute('title', normalizedTheme === 'dark' ? 'Light mode' : 'Dark mode');
    });
}

function initThemeToggle() {
    applyTheme(getInitialTheme());

    document.querySelectorAll('[data-theme-toggle]').forEach((button) => {
        if (button.dataset.initialized === 'true') return;
        button.addEventListener('click', () => {
            const nextTheme = document.body.dataset.theme === 'dark' ? 'light' : 'dark';
            localStorage.setItem('salesnews_theme', nextTheme);
            applyTheme(nextTheme);
        });
        button.dataset.initialized = 'true';
    });
}

function initUptimeCounter() {
    const startDate = new Date('2025-06-18T00:00:00+05:00');

    function updateCounter() {
        const now = new Date();
        const msPerSec = 1000;
        const msPerMin = msPerSec * 60;
        const msPerHour = msPerMin * 60;
        const msPerDay = msPerHour * 24;

        let months = (now.getFullYear() - startDate.getFullYear()) * 12 + (now.getMonth() - startDate.getMonth());

        let anniversary = new Date(startDate);
        anniversary.setMonth(startDate.getMonth() + months);

        if (now < anniversary) {
            months--;
            anniversary = new Date(startDate);
            anniversary.setMonth(startDate.getMonth() + months);
        }

        let diffMs = now - anniversary;
        if (diffMs < 0) diffMs = 0;

        const days = Math.floor(diffMs / msPerDay);
        diffMs %= msPerDay;
        const hours = Math.floor(diffMs / msPerHour);

        const elements = {
            'uptime-months': months,
            'uptime-days': days,
            'uptime-hours': hours.toString().padStart(2, '0')
        };

        for (const [id, val] of Object.entries(elements)) {
            const el = document.getElementById(id);
            if (el) el.textContent = val;
        }
    }

    updateCounter();
    setInterval(updateCounter, 1000);
}

